// The Biology class's other five animals (0x71C4C0..0x727DB8): the perch's (2), the pig's
// (4), the pigeon's (3), the rat's (1) and the turtle's (6) set-up (their textures), start
// (the stage machine: each tool's check moving the dissection on a stage) and reset (each
// stage's pins, marks, incisions, organs and the markers showing the animal's parts), and
// the markers-all-shown helper they share (0x725A20). ClassBiology.cpp is the class (its
// +0x110 is the stage here); ClassBiologyAnimals.cpp has the alien, the bat and the frog.
//
// The fields (ClassBiology.cpp's layout): +0x128 the background, +0x14C pins (+0x150 their
// positions, +0x170 pinned), +0x174 marks (+0x178, +0x198), +0x1CC incisions (+0x1D0 loop,
// +0x1DC the marker they are relative to, +0x1E8 started, +0x1EB done, +0x1FC point counts,
// +0x214 / +0x2D4 segment flags, +0x394 points: 0x40 each), +0x1338 organs (+0x133C
// positions, +0x135C removed, +0x1364 the turning direction, +0x1394 the tray image, +0x13A4
// frame counts, +0x13B4 their markers), +0x1404 markers (+0x1408 positions, +0x1488 scales,
// +0x14C8 images, +0x1508 visible), +0x1518 the tray (+0x1524 showing its item), +0x152C
// its item's scale, +0x1530 (the pigeon's pebbles).
// The resets are long tables of constants, translated from the game's code case by case
// (the floats it keeps on the x87 stack across its calls resolved) and checked against it
// in emulation, every stage. The turtle's incisions of some stages are scaled to the
// screen and placed relative to their marker. The x87 runs at 24-bit precision here: float.

