// Shape 2 of the bone overlay (0x4E48E0; shapes 0 and 1 and the caller, 0x4E8CE0, are
// in BoneOverlayShapes.cpp): 324 RwIm3DVertex triangles built from the bone matrix
// (its three axes and position, the 3x4 floats at `m`) in the shared buffer 0xBD7800,
// black at alpha 0x7F or 0, then drawn through the Im3D pipe.
//
// The game unrolls it all into 17 KB of x87 code that keeps every intermediate vector in
// its 0x98C-byte frame; this is lifted from the disassembly statement by statement, the
// frame kept as it is (L(0xN) is Ghidra's local_N, V(0xN) the vector there), so the
// same float operations run in the same order on the same values. Arithmetic is float:
// the game's x87 runs in single precision (D3D9's default FPU mode) and its double
// constants are floats widened. Checked bit for bit against the original in an
// emulator (all 324 vertices and every call's arguments). The frame is never read
// before it is written.

